/* ══════ MOTEUR DE TRADUCTION ══════ */
(function(){
  const KEY='pk-lang';
  function get(k){ return window.I18N[k] || null; }
  let _applied = null;
  /** Traduit le DOM dans la langue donnée — SANS déclencher d'événement.
   *  À utiliser après avoir injecté du HTML dynamique. */
  function translateDom(lang){
    const rtl = lang === 'ar';
    _applied = lang;
    document.documentElement.lang = lang;
    document.documentElement.dir  = rtl ? 'rtl' : 'ltr';
    document.querySelectorAll('[data-i18n]').forEach(el=>{
      const p = get(el.dataset.i18n); if(!p) return;
      const t = rtl ? p[0] : p[1];
      if(t == null) return;
      if(el.dataset.i18nHtml !== undefined) el.innerHTML = t; else el.textContent = t;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
      const p = get(el.dataset.i18nPh); if(p) el.placeholder = rtl ? p[0] : p[1];
    });
    document.querySelectorAll('[data-i18n-tt]').forEach(el=>{
      const p = get(el.dataset.i18nTt); if(p) el.title = rtl ? p[0] : p[1];
    });
    document.querySelectorAll('[data-i18n-ar]').forEach(el=>{
      el.textContent = rtl ? el.dataset.i18nAr : el.dataset.i18nFr;
    });
    document.querySelectorAll('.lgsw button').forEach(b=>b.classList.toggle('on', b.dataset.lang===lang));
    const t = document.querySelector('title'); if(t) t.textContent = rtl
      ? 'منصة الأستاذة كرجيج للغة الفرنسية' : 'Plateforme Prof. Kerdjidj — Français';
  }
  /** Change la langue : traduit le DOM, mémorise le choix, puis notifie (pk:lang).
   *  Garde anti-récursion : aucun événement si la langue n'a pas changé. */
  function set(lang){
    const prev = document.documentElement.lang;
    translateDom(lang);
    try{ localStorage.setItem(KEY, lang); }catch(e){}
    if(prev !== lang) document.dispatchEvent(new CustomEvent('pk:lang', {detail:{lang, rtl: lang==='ar'}}));
  }
  function current(){ try{ return localStorage.getItem(KEY) || 'ar'; }catch(e){ return 'ar'; } }
  window.PKi18n = {
    set, translateDom, current, get,
    t(k, lang){ const p=get(k); if(!p) return k; return (lang||current())==='ar' ? p[0] : p[1]; },
    /** alias sûr (ne JAMAIS utiliser PKi18n.apply : collision avec Function.prototype.apply) */
    use(lang){ set(lang); },
    reset(){ _applied = null; }
  };
})();
